"""Week 8 cost model for the Thorax intake design. Every component here is a box in the sketch
(lab-memo.md, section 3) and nothing else. Run: python3 cost_model.py > cost-tables.md

Price source: Claude Haiku 4.5, $1 input / $5 output per 1M tokens, platform.claude.com/pricing,
read 19 Nov 2026 (Week 7). FX: $1 = EUR 0.86 (assumption, rounded). Business days/year: 250 (course rule).
Token counts: extraction = prompt v2 measured on Llama tokens 26 Nov (644 -> 1,008 in, v1 -> v2, +56 %)
applied to my Week 6 Haiku-scale count of 796 in / 154 out -> 1,246 in / 154 out. Reply draft = estimate.
"""
FX = 0.86
P_IN, P_OUT = 1 / 1e6, 5 / 1e6                      # USD per token, Haiku 4.5
CALLS = {"extract": (1246, 154), "draft": (1500, 400)}  # tokens per call (in, out); draft = (est.)
usd_per_inquiry = sum(i * P_IN + o * P_OUT for i, o in CALLS.values())
eur_per_inquiry = usd_per_inquiry * FX
RATE = 60            # EUR/h, Thorax Studio internal floor rate (positionering.md, 21 Nov 2026)
REVIEW_MIN = 3       # Thor's check of every draft before it leaves (est.)
SAVED_MIN = 12       # reading + writing the first reply + filling the offer, per inquiry (est.)
DANGER = 0.07        # dangerous-field error rate, Haiku 4.5 + prompt v2, measured 26 Nov (2/30)
MISS = 0.10          # share of those the 3-minute review misses (assumption)
ERR_COST = 300       # one wrong gear/price promise reaching a client (Week 4 value model)

print("# Cost tables — Week 8 (generated by cost_model.py, do not edit by hand)\n")
print(f"AI cost per inquiry (2 calls: extract + draft): ${usd_per_inquiry:.4f} = **EUR {eur_per_inquiry:.4f}**\n")

print("## AI model layer at the course's three volumes (calls/day, 250 business days)\n")
print("| Calls/day | Inquiries/day | EUR/day | EUR/year |\n|---:|---:|---:|---:|")
per_call = eur_per_inquiry / 2
for c in (100, 1000, 10000):
    print(f"| {c:,} | {c//2:,} | {c*per_call:.2f} | {c*per_call*250:,.0f} |")

print("\n## Year 1 (cash vs Thor's time)\n")
inq_y1 = 7 * 12                                  # Month-1 volume held flat: 4 studio + 3 DJ per month (est.)
rows = [
    ("AI API (Year 1)", f"{inq_y1} inquiries x EUR {eur_per_inquiry:.4f}", inq_y1 * eur_per_inquiry, 0),
    ("Integration build (Thor)", "16 h x EUR 60: Apps Script call + Gmail draft + log + price lookup", 0, 16 * RATE),
    ("Regression test set (Thor)", "4 h: port run_local.py/score.py to the studio fields", 0, 4 * RATE),
    ("Infrastructure", "Firestore + Apps Script + Gmail on free tiers (already running)", 0, 0),
    ("Training / change", "1 h runbook: what to check on every draft", 0, 1 * RATE),
]
cash = sum(r[2] for r in rows); time = sum(r[3] for r in rows)
cont_c, cont_t = cash * 0.15, time * 0.15
print("| Category | How | Cash EUR | Thor's time EUR |\n|---|---|---:|---:|")
for n, h, c, t in rows:
    print(f"| {n} | {h} | {c:.2f} | {t:,.0f} |")
print(f"| Contingency 15 % | always | {cont_c:.2f} | {cont_t:,.0f} |")
print(f"| **Total** | | **{cash+cont_c:.2f}** | **{time+cont_t:,.0f}** |")
print(f"\nBudget check: cash cap EUR 300 -> {'fits' if cash+cont_c <= 300 else 'OVER'}; time cap 25 h -> "
      f"{(time+cont_t)/RATE:.1f} h, {'fits' if (time+cont_t)/RATE <= 25 else 'OVER'}.\n")

print("## Scale projection (monthly), error cost included\n")
print("| | Inquiries/month | AI calls/day | Token cost EUR/month | Review time EUR/month | Expected error cost EUR/month | **Total EUR/month** | Time saved EUR/month | Cost per correctly handled inquiry EUR |")
print("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
for label, n in (("Month 1 (launch)", 7), ("Month 6 (growth)", 15), ("Month 12 (scale)", 30)):
    tok = n * eur_per_inquiry
    rev = n * REVIEW_MIN / 60 * RATE
    err = n * DANGER * MISS * ERR_COST
    tot = tok + rev + err
    saved = n * SAVED_MIN / 60 * RATE
    correct = n * (1 - DANGER * MISS)
    print(f"| {label} | {n} | {n*2/21:.1f} | {tok:.2f} | {rev:.0f} | {err:.0f} | **{tot:.0f}** | {saved:.0f} | {tot/correct:.2f} |")
print("\nReading it: the token bill never reaches EUR 1/month. Review time and the leftover error risk are "
      "> 99 % of the running cost, so the design is built around them, not around the model price.")
